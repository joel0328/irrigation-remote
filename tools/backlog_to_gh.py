"""Print `gh issue create` commands for the drafts in backlog/issues.md.

Dry run only: review the output, then run it yourself. Labels must exist
first; the script prints `gh label create` commands for them too.

    python tools/backlog_to_gh.py > create_issues.sh
"""

from __future__ import annotations

import re
import shlex
import sys
from pathlib import Path

LABELS = {
    "research": ("0e8a16", "Find or check facts about existing products"),
    "hardware": ("d93f0b", "Boards, wiring, measurements"),
    "firmware": ("1d76db", "Firmware and protocol code"),
    "decision": ("fbca04", "Needs a decision by Joel or the friend"),
    "vendor": ("5319e7", "Contact with a vendor (sent by a person, not automated)"),
}


def parse(text: str):
    issues = []
    for block in re.split(r"^## ", text, flags=re.M)[1:]:
        lines = block.strip().splitlines()
        title = lines[0].strip()
        labels, body = [], []
        for line in lines[1:]:
            if line.startswith("labels:"):
                labels = [s.strip() for s in line[len("labels:"):].split(",") if s.strip()]
            else:
                body.append(line)
        issues.append((title, labels, "\n".join(body).strip()))
    return issues


def main() -> int:
    path = Path(__file__).resolve().parent.parent / "backlog" / "issues.md"
    issues = parse(path.read_text(encoding="utf-8"))
    bad = [(t, l) for t, ls, _ in issues for l in ls if l not in LABELS]
    if bad:
        for t, l in bad:
            print(f"unknown label {l!r} in {t!r}", file=sys.stderr)
        return 1
    print("# Generated by tools/backlog_to_gh.py. Review before running.")
    for name, (color, desc) in LABELS.items():
        print(f"gh label create {name} --color {color} --description {shlex.quote(desc)} --force")
    for title, labels, body in issues:
        args = ["gh", "issue", "create", "--title", title, "--body", body or title]
        for l in labels:
            args += ["--label", l]
        print(shlex.join(args))
    print(f"# {len(issues)} issues", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
